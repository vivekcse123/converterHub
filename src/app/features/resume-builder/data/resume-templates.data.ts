/**
 * Returns the default hex accent colour for a template.
 * Prefers `defaultAccentHex` (explicit override) over the colour derived from the gradient chip.
 */
export function getTemplateDefaultAccent(meta: ResumeTemplateMeta): string {
  if (meta.defaultAccentHex) return meta.defaultAccentHex;
  const token = meta.accent.split(' ')[0].replace('from-', '');
  return TW_HEX[token] ?? '#1e293b';
}

/** Convenience helper — looks up template by id and returns its default accent hex. */
export function getDefaultAccentById(templateId: TemplateId): string {
  const meta = RESUME_TEMPLATES.find(t => t.id === templateId);
  return meta ? getTemplateDefaultAccent(meta) : '#1e293b';
}

export function getTemplateMeta(id: TemplateId): ResumeTemplateMeta {
  return RESUME_TEMPLATES.find(t => t.id === id) ?? RESUME_TEMPLATES[0];
}

export function getTemplateBySlug(slug: string): ResumeTemplateMeta | undefined {
  return RESUME_TEMPLATES.find(t => t.slug === slug);
}

/** ATS-friendliness threshold shown as a badge/filter — single source of truth. */
export const ATS_FRIENDLY_THRESHOLD = 90;

export function isAtsFriendly(meta: ResumeTemplateMeta): boolean {
  return meta.atsScore >= ATS_FRIENDLY_THRESHOLD;
}

export function isPhotoResume(meta: ResumeTemplateMeta): boolean {
  return !!meta.photoEnabled;
}

