export interface ResumeTemplateMeta {
  id: TemplateId;
  slug: string;
  name: string;
  description: string;
  component: Type<unknown>;
  /** Tailwind gradient classes used for the template card color chip. */
  accent: string;
  /**
   * The hex value of the CSS --r-accent custom property for this template's default appearance.
   * When set, this is the single source of truth for the template's accent colour everywhere
   * (home page, gallery, editor, PDF). Overrides the colour derived from `accent` gradient.
   */
  defaultAccentHex?: string;
  bestFor: string;
  category: TemplateCategory;
  isPremium: boolean;
  /** If true, the template renders the user's profile photo when present. */
  photoEnabled?: boolean;
  /** Fine-grained style/role/layout tags — see `TEMPLATE_TAG_GROUPS`. */
  tags: TemplateTag[];
  /** Typical rendered length for the sample resume — shown as a gallery card indicator. */
  pageCount: 1 | 2;
  /** Marks a template as part of the most recent batch, for the "Newest" sort/filter. */
  isNew?: boolean;
  atsScore: number;
  sections: string[];
  suitableFor: string[];
  industries: TemplateIndustry[];
  experienceLevels: ExperienceLevel[];
  downloads: number;
  rating: number;
  isPopular: boolean;
  isEditorChoice: boolean;
  isTrending: boolean;
  atsExplanation: string;
}

